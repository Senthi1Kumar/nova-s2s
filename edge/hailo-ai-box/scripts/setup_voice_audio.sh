#!/usr/bin/env bash
# Configure the AI Box microphone-specific echo-cancellation route.
# XVF3800 uses onboard AEC. WM8960 uses PipeWire WebRTC AEC with playback reference.
set -euo pipefail

CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/pipewire/pipewire.conf.d"
CONF="$CONF_DIR/99-aibox-echo-cancel.conf"
CHECK_ONLY="${AIBOX_AEC_CHECK:-0}"

if grep -qi "XVF3800" /proc/asound/cards 2>/dev/null; then
  echo "[voice] XVF3800 detected: onboard AEC path (ch1 = AEC residual, no NS/AGC)"
  if [[ "$CHECK_ONLY" != "1" && -f "$CONF" ]]; then
    rm -f "$CONF"
    systemctl --user restart pipewire pipewire-pulse wireplumber 2>/dev/null || true
  fi
  exit 0
fi

if ! grep -qi "wm8960" /proc/asound/cards 2>/dev/null; then
  echo "[voice] no XVF3800 or WM8960 detected: generic/default audio path"
  exit 0
fi

if ! command -v pipewire >/dev/null 2>&1 || ! command -v pactl >/dev/null 2>&1; then
  echo "[voice] WM8960 needs PipeWire and pulseaudio-utils for playback-reference AEC" >&2
  exit 1
fi

MIC_TARGET="${AIBOX_AEC_MIC_TARGET:-}"
SPK_TARGET="${AIBOX_AEC_SPK_TARGET:-}"
if [[ -z "$MIC_TARGET" ]]; then
  MIC_TARGET=$(pactl list short sources 2>/dev/null \
    | awk '/wm8960|WM8960/ && $2 !~ /\.monitor$/ {print $2; exit}' || true)
fi
if [[ -z "$SPK_TARGET" ]]; then
  SPK_TARGET=$(pactl list short sinks 2>/dev/null | awk '/wm8960|WM8960/ {print $2; exit}' || true)
fi
mic_line=""
spk_line=""
[[ -z "$MIC_TARGET" ]] || mic_line="                target.object = \"$MIC_TARGET\""
[[ -z "$SPK_TARGET" ]] || spk_line="                target.object = \"$SPK_TARGET\""

NEW_CONF=$(mktemp)
trap 'rm -f "$NEW_CONF"' EXIT
cat >"$NEW_CONF" <<EOF
# Generated by AI Box scripts/setup_voice_audio.sh.
context.modules = [
  { name = libpipewire-module-echo-cancel
    args = {
      library.name = aec/libspa-aec-webrtc
      audio.channels = 1
      aec.args = {
        webrtc.extended_filter = true
        webrtc.delay_agnostic = true
        webrtc.high_pass_filter = true
        webrtc.noise_suppression = false
        webrtc.gain_control = false
      }
      capture.props = {
        node.name = "echo-cancel-capture"
        node.passive = true
${mic_line}
      }
      source.props = {
        node.name = "echo-cancel-source"
        node.description = "AI Box echo-cancel source"
      }
      sink.props = {
        node.name = "echo-cancel-sink"
        node.description = "AI Box echo-cancel sink"
      }
      playback.props = {
        node.name = "echo-cancel-playback"
        node.passive = true
${spk_line}
      }
    }
  }
]
EOF

if [[ "$CHECK_ONLY" == "1" ]]; then
  if [[ -f "$CONF" ]]; then
    echo "[voice] WM8960 AEC configuration exists: $CONF"
  else
    echo "[voice] WM8960 AEC configuration is missing: $CONF" >&2
    exit 1
  fi
  exit 0
fi

mkdir -p "$CONF_DIR"
changed=0
if [[ ! -f "$CONF" ]] || ! cmp -s "$NEW_CONF" "$CONF"; then
  cp "$NEW_CONF" "$CONF"
  changed=1
  echo "[voice] wrote WM8960 playback-reference AEC: $CONF"
else
  echo "[voice] WM8960 AEC already configured"
fi
if ((changed)); then
  systemctl --user restart pipewire pipewire-pulse wireplumber 2>/dev/null || true
fi
cat <<'EOF'
[voice] WM8960 route: playback=echo-cancel-sink capture=echo-cancel-source
        PortAudio uses "pulse" with PULSE_SINK/PULSE_SOURCE; do not open the raw codec.
EOF
