#!/usr/bin/env bash
# Enable PipeWire WebRTC echo-cancel for the WM8960 HMI path.
#
# Writes ~/.config/pipewire/pipewire.conf.d/99-nova-echo-cancel.conf.
# Restarts the user PipeWire session only when the conf actually changed
# (so run_demo_oem.sh can call this every start without killing HMI audio).
# Non-fatal if PipeWire is not running (laptop unit tests).
set -euo pipefail

CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/pipewire/pipewire.conf.d"
CONF="$CONF_DIR/99-nova-echo-cancel.conf"
MIC_TARGET="${NOVA_AEC_MIC_TARGET:-}"
SPK_TARGET="${NOVA_AEC_SPK_TARGET:-}"

mkdir -p "$CONF_DIR"

# Prefer a WM8960 node when one is already enumerated; otherwise leave
# target.object unset so PipeWire follows the default source/sink.
if [[ -z "$MIC_TARGET" ]] && command -v pactl >/dev/null 2>&1; then
  MIC_TARGET=$(pactl list short sources 2>/dev/null | awk '/wm8960|WM8960/ && $2 !~ /\.monitor$/ { print $2; exit }' || true)
fi
if [[ -z "$SPK_TARGET" ]] && command -v pactl >/dev/null 2>&1; then
  SPK_TARGET=$(pactl list short sinks 2>/dev/null | awk '/wm8960|WM8960/ { print $2; exit }' || true)
fi

mic_line=""
spk_line=""
if [[ -n "$MIC_TARGET" ]]; then
  mic_line="                target.object = \"$MIC_TARGET\""
fi
if [[ -n "$SPK_TARGET" ]]; then
  spk_line="                target.object = \"$SPK_TARGET\""
fi

NEW_CONF=$(mktemp)
trap 'rm -f "$NEW_CONF"' EXIT
cat > "$NEW_CONF" <<EOF
# Generated by scripts/setup_pipewire_aec.sh — Nova HMI WM8960 AEC.
context.modules = [
  {   name = libpipewire-module-echo-cancel
      args = {
          library.name = aec/libspa-aec-webrtc
          audio.channels = 1
          aec.args = {
              webrtc.extended_filter = true
              webrtc.delay_agnostic = true
              webrtc.high_pass_filter = true
              webrtc.noise_suppression = false
              webrtc.gain_control = false
          }
          capture.props = {
              node.name = "echo-cancel-capture"
              node.passive = true
${mic_line}
          }
          source.props = {
              node.name = "echo-cancel-source"
              node.description = "Nova echo-cancel source"
          }
          sink.props = {
              node.name = "echo-cancel-sink"
              node.description = "Nova echo-cancel sink"
          }
          playback.props = {
              node.name = "echo-cancel-playback"
              node.passive = true
${spk_line}
          }
      }
  }
]
EOF

changed=1
if [[ -f "$CONF" ]] && cmp -s "$NEW_CONF" "$CONF"; then
  changed=0
  echo "[aec] already configured ($CONF)"
else
  cp "$NEW_CONF" "$CONF"
  echo "[aec] wrote $CONF"
fi
if [[ -n "$MIC_TARGET" ]]; then
  echo "[aec] mic target: $MIC_TARGET"
fi
if [[ -n "$SPK_TARGET" ]]; then
  echo "[aec] speaker target: $SPK_TARGET"
fi

if [[ "$changed" -eq 1 ]] && command -v systemctl >/dev/null 2>&1; then
  if systemctl --user restart pipewire pipewire-pulse wireplumber 2>/dev/null; then
    echo "[aec] restarted pipewire (user session)"
  else
    echo "[aec] pipewire restart skipped (not running as a user service)"
  fi
fi

if [[ "${NOVA_AEC_QUIET:-}" != "1" ]]; then
  cat <<'HINT'

Point the Qt HMI at the virtual nodes (run_demo_oem.sh / hmi_qt/run.sh do this):

  export NOVA_HAILO_CAPTURE_DEVICE="echo-cancel-source"
  export NOVA_HAILO_PLAYBACK_DEVICE="echo-cancel-sink"

See docs/pipewire-aec.md.

HINT
fi
