#!/usr/bin/env python3
"""Regenerate src/map/mapbox_logo.c: the Mapbox wordmark that Mapbox's terms require on maps drawn with its
styles, taken from Mapbox GL JS's own stylesheet (.mapboxgl-ctrl-logo) so it is the official artwork.

    curl -sSfLo /tmp/mapbox-gl.css https://unpkg.com/mapbox-gl@3.9.4/dist/mapbox-gl.css
    python3 tools/gen_mapbox_logo.py /tmp/mapbox-gl.css src/map/mapbox_logo.c

Needs rsvg-convert (librsvg) and Pillow. The image is 88 x 23, the size GL JS draws it, as LVGL ARGB8888
(B, G, R, A per pixel, straight alpha).
"""
import io
import re
import subprocess
import sys
import urllib.parse

from PIL import Image

W, H = 88, 23


def main(css_path: str, out_path: str) -> None:
    css = open(css_path, encoding="utf-8").read()
    m = re.search(r'\.mapboxgl-ctrl-logo\{[^}]*?background-image:url\("data:image/svg\+xml;charset=utf-8,([^"]+)"\)',
                  css)
    if not m:
        sys.exit("no .mapboxgl-ctrl-logo data URI in " + css_path)
    svg = urllib.parse.unquote(m.group(1)).encode()
    png = subprocess.run(["rsvg-convert", "-w", str(W), "-h", str(H)], input=svg, capture_output=True,
                         check=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    px = []
    for y in range(H):
        for x in range(W):
            r, g, b, a = im.getpixel((x, y))
            px += [b, g, r, a]
    rows = [", ".join(f"0x{v:02x}" for v in px[i:i + 16]) for i in range(0, len(px), 16)]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_mapbox_logo.py from Mapbox GL JS's .mapboxgl-ctrl-logo. Do not edit. */\n")
        f.write('#include "map/mapbox_logo.h"\n\n')
        f.write(f"static const uint8_t k_px[{len(px)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n\n")
        f.write("const lv_image_dsc_t cb_mapbox_logo = {\n")
        f.write(f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = {W}, .h = {H},\n")
        f.write(f"                .stride = {W * 4} }},\n")
        f.write("    .data_size = sizeof k_px,\n    .data = k_px,\n};\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
